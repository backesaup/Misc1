// Regenerates docs/asset-index/: machine-built lists of everything lessons can draw on.
//   node scripts/build-asset-index.mjs
// - every Minecraft block and item (Java + Bedrock) with stack sizes, from PrismarineJS minecraft-data
// - every texture file in each source repo listed in content/textures.json (needs internet + GitHub API;
//   set GITHUB_TOKEN to avoid rate limits). Sources that can't be listed are noted, not guessed.
// - what is currently downloaded into src/assets/textures/
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'docs/asset-index')
mkdirSync(out, { recursive: true })
const require = createRequire(import.meta.url)
const mcData = require('minecraft-data')

// 1. Blocks and items
const java = mcData('1.21.4')
const bedrock = mcData('bedrock_1.21.0')
const names = new Set([...Object.keys(java.itemsByName), ...Object.keys(bedrock.itemsByName)])
const rows = [...names].sort().map((n) => {
  const j = java.itemsByName[n], b = bedrock.itemsByName[n]
  const isBlock = !!(java.blocksByName[n] || bedrock.blocksByName[n])
  return `| \`${n}\` | ${(j ?? b).displayName} | ${isBlock ? 'block' : 'item'} | ${j ? j.stackSize : '—'} | ${b ? b.stackSize : '—'} |`
})
writeFileSync(
  join(out, 'minecraft-items.md'),
  `# Minecraft blocks and items\n\nGenerated by \`scripts/build-asset-index.mjs\` from PrismarineJS minecraft-data (Java 1.21.4, Bedrock 1.21.0). ${rows.length} entries.\nStack sizes come from the data files; double-check any fact a lesson relies on (the data has been wrong before, e.g. Bedrock cake).\n\n| id | name | kind | Java stack | Bedrock stack |\n|---|---|---|---|---|\n${rows.join('\n')}\n`,
)
const foods = java.foodsArray.map((f) => `| \`${f.name}\` | ${f.displayName} | ${f.foodPoints} | ${f.saturation} |`)
writeFileSync(join(out, 'minecraft-foods.md'), `# Minecraft foods (Java 1.21.4)\n\nGenerated from minecraft-data.\n\n| id | name | food points | saturation |\n|---|---|---|---|\n${foods.join('\n')}\n`)

// 2. Texture files per source repo
const manifest = JSON.parse(readFileSync(join(root, 'content/textures.json'), 'utf8'))
const headers = { 'User-Agent': 'asset-index', ...(process.env.GITHUB_TOKEN ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}) }
const sections = []
for (const [id, s] of Object.entries(manifest.sources)) {
  let body
  try {
    const res = await fetch(`https://api.github.com/repos/${s.repo}/git/trees/${encodeURIComponent(s.branch)}?recursive=1`, { headers })
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    const tree = (await res.json()).tree ?? []
    const files = tree.filter((t) => t.type === 'blob' && /\.png$/i.test(t.path) && /textures?\//i.test(t.path)).map((t) => t.path)
    body = files.length ? `${files.length} texture files.\n\n<details><summary>List</summary>\n\n${files.map((f) => `- \`${f}\``).join('\n')}\n\n</details>` : 'No texture files found on this branch.'
  } catch (e) {
    body = `Could not list (${e.message}). Run this script on a machine with internet access (set GITHUB_TOKEN if rate-limited).`
  }
  sections.push(`## ${id}: ${s.repo}@${s.branch}\n\nEdition: ${s.edition}. Licence: ${s.licence}. Base path: \`${s.base || '(unknown)'}\`.\n\n${body}`)
}
writeFileSync(join(out, 'texture-sources.md'), `# Texture sources\n\nGenerated by \`scripts/build-asset-index.mjs\`. Add a block to \`content/textures.json\` (key → candidates "source:path") to use any of these.\n\n${sections.join('\n\n')}\n`)

// 3. Downloaded now
const local = existsSync(join(root, 'src/assets/textures')) ? readdirSync(join(root, 'src/assets/textures')) : []
writeFileSync(join(out, 'downloaded-textures.md'), `# Downloaded textures\n\nFiles in \`src/assets/textures/\` when the index was built (gitignored; fetch with \`npm run textures:fetch\`).\n\n${local.map((f) => `- \`${f}\``).join('\n') || '(none)'}\n`)
console.log(`asset index: ${rows.length} items, ${foods.length} foods, ${sections.length} texture sources, ${local.length} downloaded`)
